import Pkg
import TOML
import UUIDs: UUID

const ENGINE_ROOT = normpath(joinpath(@__DIR__, ".."))
const ENVIRONMENT_ROOT = joinpath(ENGINE_ROOT, "environments")
const VERSIONS = TOML.parsefile(joinpath(ENVIRONMENT_ROOT, "versions.toml"))
const ENGINE_PROJECT = TOML.parsefile(joinpath(ENGINE_ROOT, "Project.toml"))
const ENGINE_UUID = UUID(ENGINE_PROJECT["uuid"])
const HEADER = """
# SPDX-FileCopyrightText: 2026 John C. Travers and contributors
# SPDX-License-Identifier: GPL-3.0-or-later
# Generated by scripts/resolve.jl; edit its inputs, then regenerate.

"""

function write_project(name, dependencies, compatibility; engine = true)
    directory = joinpath(ENVIRONMENT_ROOT, name)
    mkpath(directory)
    project = Dict{String, Any}("deps" => dependencies, "compat" => compatibility)
    version = VersionNumber(VERSIONS["julia"])
    project["compat"]["julia"] = "~$(version.major).$(version.minor).0"
    if engine
        project["deps"]["SolpropJulia"] = string(ENGINE_UUID)
        project["sources"] = Dict("SolpropJulia" => Dict("path" => "../.."))
    end
    open(joinpath(directory, "Project.toml"), "w") do io
        print(io, HEADER)
        TOML.print(io, project; sorted = true)
    end
    return directory
end

function derive_manifest(name, joint)
    project_file = joinpath(ENVIRONMENT_ROOT, name, "Project.toml")
    environment = Pkg.Types.EnvCache(project_file)
    roots = Set(values(environment.project.deps))
    environment.manifest = Pkg.Operations.prune_manifest(deepcopy(joint), roots)
    Pkg.Operations.record_project_hash(environment)
    Pkg.Types.write_manifest(environment)
    return nothing
end

function resolve_environments()
    VERSION == VersionNumber(VERSIONS["julia"]) || throw(
        ArgumentError(
            "resolve with Julia $(VERSIONS["julia"]), not $VERSION",
        )
    )
    ENV["JULIA_PKG_PRECOMPILE_AUTO"] = "0"
    weak = ENGINE_PROJECT["weakdeps"]
    bridge = Dict("PythonCall" => weak["PythonCall"])
    bridge_compat = Dict("PythonCall" => "=" * VERSIONS["PythonCall"])
    names = (cuda = "CUDA", rocm = "AMDGPU", metal = "Metal")
    joint_dependencies = copy(bridge)
    joint_compat = copy(bridge_compat)
    write_project("cpu", copy(bridge), copy(bridge_compat))
    for (environment, package) in pairs(names)
        dependencies = Dict(package => weak[package])
        compatibility = Dict(package => ENGINE_PROJECT["compat"][package])
        if environment == :cuda
            # Artifact selectors read these preferences without loading a GPU driver.
            dependencies["CUDA_Runtime_jll"] = "76a88914-d11a-5bdc-97e0-2f5a05c973a2"
            dependencies["CUDA_Compiler_jll"] = "d1e2174e-dfdc-576e-b43e-73b79eb1aca8"
            compatibility["CUDA_Runtime_jll"] = "0.25"
            compatibility["CUDA_Compiler_jll"] = "0.6"
        end
        merge!(joint_dependencies, dependencies)
        merge!(joint_compat, compatibility)
        write_project(string(environment), dependencies, compatibility)
    end
    joint_directory = write_project("joint", joint_dependencies, joint_compat)
    Pkg.activate(joint_directory)
    Pkg.resolve()
    joint = Pkg.Types.read_manifest(joinpath(joint_directory, "Manifest.toml"))
    for name in ("cpu", "cuda", "rocm", "metal")
        derive_manifest(name, joint)
    end

    quality_dependencies = Dict(
        "Aqua" => "4c88cf16-eb10-579e-8560-4a9242c79595",
        "JET" => "c3a54625-cd67-489e-a8e7-0a5a0ff4e31b",
        "Test" => "8dfed614-e22c-5e08-85e1-65c5234f0b40",
    )
    quality_compat = Dict(
        "Aqua" => "=" * VERSIONS["Aqua"],
        "JET" => "=" * VERSIONS["JET"],
        "Test" => "1.11",
    )
    quality_directory = write_project("quality", quality_dependencies, quality_compat)
    Pkg.activate(quality_directory)
    Pkg.resolve()

    formatter_directory = write_project(
        "formatter",
        Dict("Runic" => "62bfec6d-59d7-401d-8490-b29ee721c001"),
        Dict("Runic" => "=" * VERSIONS["Runic"]);
        engine = false,
    )
    Pkg.activate(formatter_directory)
    Pkg.resolve()
    return nothing
end

resolve_environments()
