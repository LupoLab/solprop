"""
    TemporalMonitorRecord

Retain detached temporal continuation and already computed public summary scalars.

`continuation` is the existing fifteen-field `TemporalContinuation`, with live quiet
count presence. `removed_signed`, its nonnegative `removed_fraction`, and `noise_floor`
are dimensionless energy shares in the reference monitor's operation order. `resuming`
is the unconsumed continuation flag, and `committed` is the last monitor position in m
or NaN before attachment. Together they identify a resumed launch even if a later
operation fails before the services' started flag is set. No arrays or Python objects
are retained. Unmeasured launch/position metadata preserve their documented NaNs.
"""
struct TemporalMonitorRecord
    continuation::TemporalContinuation
    removed_signed::Float64
    removed_fraction::Float64
    noise_floor::Float64
    resuming::Bool
    committed::Float64
end

"""
    SessionMonitorPayload

Describe one generation's detached monitor records, rows and already decided notices.

`record` is an optional `TemporalMonitorRecord`; `transverse` is an optional
`TransverseMonitorRecord` with its fixed face tuples. `row_count` counts only temporal
rows and is between zero and two. `notice`
is either nothing or the single pending `MonitorNotice`, and `crossing` is either
nothing or a `TemporalCrossingRefusal`. The latter records contain only numerical
facts for external formatting, never a callback or an exception. `attached` is the
session's services-started fact, including a failed launch, and `finished` is the
service's completed finish-hook fact. Reading this immutable pointer-free record
neither drains buffers nor changes a monitor or session decision.
`resuming` and `committed` are the temporal lifecycle facts when that monitor exists;
otherwise they identify an unconsumed edge attachment and its committed coordinate.
They remain distinct from transverse `resumed`, which means positive totals restored.
"""
struct SessionMonitorPayload{T}
    record::Union{Nothing, TemporalMonitorRecord}
    transverse::T
    row_count::Int
    notice::Union{Nothing, MonitorNotice}
    crossing::Union{Nothing, TemporalCrossingRefusal}
    attached::Bool
    finished::Bool
    resuming::Bool
    committed::Float64
end

function _monitor_transfer_generation(session, generation)
    state = session.state
    if generation == 0
        !state.closed && !state.finished && !state.pending &&
            state.generation == 0 && !state.services_started ||
            throw(ArgumentError("initial monitor reads require an unadvanced open session"))
    else
        _session_chunk_pending(session, generation)
    end
    return nothing
end

"""
    session_monitor_payload(session, generation)

Read detached numerical monitor data without draining the pending generation.

Return a `SessionMonitorPayload` whenever either monitor exists, including before
attachment, or nothing for an unmonitored session. A zero generation is allowed only
for an open nonpending session whose generation is zero and services have not started;
a resumed constructor may already mark its launch event as delivered. Every later
read requires the exact pending generation. Poisoned and terminal pending events still
permit diagnostic reads. Invalid lifetimes or corrupt bounded counts raise before
mutation; no numerical hook or notice is generated by this call.
"""
function session_monitor_payload(session, generation::Int)
    _monitor_transfer_generation(session, generation)
    services = session.services
    services isa ObservationServices || return nothing
    state = services.work.monitor
    transverse = services.transverse
    state === nothing && transverse === nothing && return nothing
    0 <= services.monitor_count <= 2 &&
        services.monitor_count <= length(services.monitor_rows) &&
        0 <= services.notices.count <= 1 &&
        services.notices.count <= length(services.notices.records) ||
        throw(ArgumentError("monitor transport counts exceed their fixed buffers"))
    record = if state === nothing
        nothing
    else
        removed = temporal_removed(state)
        TemporalMonitorRecord(
            temporal_continuation(state), removed, max(removed, 0.0),
            state.launch > 0.0 ? state.floor / state.launch : 0.0,
            state.resuming, state.committed,
        )
    end
    notice = services.notices.count == 0 ? nothing : services.notices.records[1]
    return SessionMonitorPayload(
        record, transverse === nothing ? nothing : transverse_monitor_record(transverse),
        services.monitor_count, notice, services.crossing_refusal,
        session.state.services_started, services.finished,
        state === nothing ? services.resume_pending && !transverse.started : state.resuming,
        state === nothing ? transverse.committed_z : state.committed,
    )
end


"""
    session_monitor_rows!(rows, session, generation)

Copy a generation's temporal plane rows to detached binary64 destination storage.

The one-based writable matrix `rows` has shape `(5,row_count)`. Its first axis is
`z` in m, collar occupancy, low guard occupancy, high guard occupancy and nonnegative
removed fraction; the last four are dimensionless. Empty payloads require `(5,0)`.
Check lifetime, dimensions and overlap with all retained session/service arrays before
writing. Preserve unmeasured NaNs, retained rows and counters so a failed copy is
retryable. Only the existing valid event acknowledgment clears the payload.
"""
function session_monitor_rows!(
        rows::AbstractMatrix{Float64}, session, generation::Int,
    )
    payload = session_monitor_payload(session, generation)
    count = payload === nothing ? 0 : payload.row_count
    size(rows) == (5, count) ||
        throw(DimensionMismatch("temporal monitor rows require shape (5,row_count)"))
    Base.require_one_based_indexing(rows)
    _transfer_writable_destination(rows)
    _retained_alias(rows, (session, session.services)) &&
        throw(ArgumentError("temporal monitor rows must not alias retained storage"))
    payload === nothing && return nothing
    services = session.services
    for index in 1:count
        row = services.monitor_rows[index]
        rows[1, index], rows[2, index] = row.z, row.collar
        rows[3, index], rows[4, index] = row.guard_low, row.guard_high
        rows[5, index] = row.removed
    end
    return nothing
end

