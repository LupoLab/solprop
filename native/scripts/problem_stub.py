"""Write ``_core.pyi`` and ``_core_testing.pyi`` from ``nanobind.stubgen``.

Both stubs are generated whole (solprop SEP 52 section 5.3): the extension's module
and its private test module ``_core._testing``. The bindings give each record argument
and result a signature naming its Python record (``nb::sig``), so the stubs stay
typed; this script only rewrites stubgen's spellings into the stubs' own: an array
caster's ``Annotated[NDArray[...], ...]`` as ``npt.NDArray[...]``, a bare ``dict``,
``tuple`` or ``list`` with its parameters, a problem group's property and setter as a
plain attribute (an array field is copied in and out: assign a whole array), and the
imports each stub uses. ``--check`` exits 1 instead when a committed stub differs (the
native lint stage).
"""

import re
import subprocess
import sys
from pathlib import Path
from types import ModuleType

from nanobind.stubgen import StubGen

import solprop_native._core as core

STUB = Path(__file__).resolve().parents[1] / "src/solprop_native/_core.pyi"
TESTING_STUB = STUB.with_name("_core_testing.pyi")
HEADER = """\
# SPDX-FileCopyrightText: 2026 John C. Travers and contributors
#
# SPDX-License-Identifier: GPL-3.0-or-later

# Generated by native/scripts/problem_stub.py from nanobind.stubgen: do not edit.
"""
PAIR = re.compile(
    r"@property\n(\s*)def (\w+)\(self\) -> (.+): \.\.\.\n\n"
    r"\s*@\2\.setter\n\s*def \2\(self, arg: (.+), /\) -> None: \.\.\."
)
ARRAY = re.compile(r"Annotated\[NDArray\[numpy\.(\w+)\], dict\(")
IMPORTS = {
    "enum.": "import enum",
    "Any": "from typing import Any",
    "overload": "from typing import overload",
    "Mapping": "from collections.abc import Mapping",
    "Sequence": "from collections.abc import Sequence",
    "Callable": "from collections.abc import Callable",
    "np.": "import numpy as np",
    "npt.": "import numpy.typing as npt",
    "solprop.backends.records.": "import solprop.backends.records",
    "solprop.backends.engines.": "import solprop.backends.engines",
}


def _arrays(text: str) -> str:
    """Return `text` with each array caster's annotation as ``npt.NDArray[np.X]``."""
    out: list[str] = []
    position = 0
    while (match := ARRAY.search(text, position)) is not None:
        out.append(text[position : match.start()])
        out.append(f"npt.NDArray[np.{match.group(1)}]")
        # Skip the caster's `dict(...)` and the closing bracket, parentheses balanced.
        depth, index = 1, match.end()
        while depth:
            depth += {"(": 1, ")": -1}.get(text[index], 0)
            index += 1
        position = index + 1
    out.append(text[position:])
    return "".join(out)


def _body(module: ModuleType, names: list[str] | None = None) -> str:
    """Return stubgen's stub of `module`'s names, in the stubs' spellings, no imports."""
    stub = StubGen(module, quiet=True, include_docstrings=False)
    for name in names if names is not None else sorted(vars(module)):
        if name.startswith("__") or name == "_testing":
            continue
        stub.put(getattr(module, name), name)
    text = _arrays(stub.get())
    text = PAIR.sub(r"\2: \4", text)
    lines = [
        line
        for line in text.splitlines()
        if not line.startswith(("import ", "from "))
    ]
    text = "\n".join(lines).strip() + "\n"
    replacements = {
        "numpy.typing.NDArray[numpy.": "npt.NDArray[np.",
        "collections.abc.": "",
        "typing.": "",
        "solprop_native._core.": "",
    }
    for old, new in replacements.items():
        text = text.replace(old, new)
    text = re.sub(r"\bdict\b(?!\[)", "dict[str, Any]", text)
    text = re.sub(r"\btuple\b(?!\[)", "tuple[Any, ...]", text)
    text = re.sub(r"\blist\b(?!\[)", "list[Any]", text)
    return text


def _imports(body: str, extra: list[str]) -> str:
    """Return the import lines `body` uses, and `extra`."""
    lines = sorted({line for token, line in IMPORTS.items() if token in body})
    return "\n".join(["from __future__ import annotations", "", *lines, *extra]) + "\n"


def _formatted(text: str, path: Path) -> str:
    """Return `text` with its imports sorted and formatted, as ruff leaves a stub."""
    ruff = [sys.executable, "-m", "ruff"]
    for command in (
        ["check", "--fix", "--select", "I", "--quiet", "--exit-zero"],
        ["format"],
    ):
        text = subprocess.run(
            [*ruff, *command, "--stdin-filename", str(path), "-"],
            input=text,
            capture_output=True,
            text=True,
            check=True,
        ).stdout
    return text


def generated() -> dict[Path, str]:
    """Return both stubs' text, formatted as ruff formats a stub."""
    body = _body(core)
    extra = [
        "",
        "# The private test module, bound as the submodule `_testing` (solprop SEP 52):",
        "# its stub is `_core_testing.pyi`; the extension has no `_core_testing`.",
        "from solprop_native import _core_testing",
        "",
        "_testing = _core_testing",
    ]
    main = HEADER + "\n" + _imports(body, extra) + "\n" + body
    testing = _body(core._testing)  # pyright: ignore[reportPrivateUsage]
    bound = sorted(
        name
        for name in vars(core)
        if not name.startswith("_") and re.search(rf"\b{name}\b", testing)
    )
    testing_extra = [f"from solprop_native._core import {', '.join(bound)}"]
    private = (
        HEADER
        + "# The private test module `solprop_native._core._testing` (solprop SEP 52 "
        "section 6.5):\n# the entry points only solprop's own tests reach. It promises"
        " nothing.\n\n"
        + _imports(testing, testing_extra)
        + "\n"
        + testing
    )
    return {STUB: _formatted(main, STUB), TESTING_STUB: _formatted(private, STUB)}


def main(argv: list[str]) -> int:
    """Write both stubs, or with ``--check`` report whether either is stale."""
    stale = []
    for path, text in generated().items():
        if path.read_text(encoding="utf-8") != text:
            if "--check" not in argv:
                path.write_text(text, encoding="utf-8")
            stale.append(path.name)
    if stale and "--check" in argv:
        print(f"{', '.join(stale)} stale: run native/scripts/problem_stub.py")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
