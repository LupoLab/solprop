"""Write the bound problem's part of ``_core.pyi`` from ``nanobind.stubgen``.

The extension binds ``FieldFamily`` and the nested ``Problem`` aggregates; stubgen
writes each field as a property and its setter, typed by the array caster. This keeps
the setter's type as a plain attribute, so the stub stays short and strict pyright
accepts the adapter's assignments, and replaces the text between the stub's markers.
``--check`` exits 1 instead when the committed stub differs (the native lint stage).
"""

import re
import subprocess
import sys
from pathlib import Path

from nanobind.stubgen import StubGen

import solprop_native._core as core

STUB = Path(__file__).resolve().parents[1] / "src/solprop_native/_core.pyi"
BEGIN = (
    "# Generated by native/scripts/problem_stub.py from nanobind.stubgen.\n"
    "# Array fields are copied in and out: assign a whole array, since an item\n"
    "# assigned through a read copy changes nothing.\n"
)
END = "\n# End of the generated problem stub.\n"
PAIR = re.compile(
    r"@property\n\s*def (\w+)\(self\) -> .+: \.\.\.\n\n"
    r"\s*@\1\.setter\n\s*def \1\(self, arg: (.+), /\) -> None: \.\.\."
)


def generated() -> str:
    """Return the problem's stub section, formatted as ruff formats a stub."""
    stub = StubGen(core, quiet=True, include_docstrings=False)
    for name in ("FieldFamily", "Problem"):
        stub.put(getattr(core, name), name)
    text = PAIR.sub(r"\1: \2", stub.get())
    text = text.replace("numpy.typing.NDArray[numpy.", "npt.NDArray[np.")
    text = text[text.index("class FieldFamily") :]
    text = re.sub(r"\n\n( +\w+: )", r"\n\1", text)
    text = re.sub(r"(def __init__\(self\) -> None: \.\.\.)\n\n", r"\1\n", text)
    formatted = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", str(STUB), "-"],
        input=text,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    return BEGIN + formatted + END


def main(argv: list[str]) -> int:
    """Rewrite the section, or with ``--check`` report whether it is stale."""
    text = STUB.read_text(encoding="utf-8")
    # The section runs from the marker's first line to the end marker.
    start = text.index(BEGIN.splitlines(keepends=True)[0])
    end = text.index(END, start) + len(END)
    head, current, tail = text[:start], text[start:end], text[end:]
    fresh = generated()
    if "--check" in argv:
        if current != fresh:
            print(f"{STUB.name} is stale: run native/scripts/problem_stub.py")
            return 1
        return 0
    STUB.write_text(head + fresh + tail, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
