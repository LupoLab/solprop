"""Decision traces of the Runge-Kutta march on scripted norms (SEP 45 section 7.2).

The march's controller is driven through a stub backend whose trial returns, for each
attempt, the norm a scenario prescribes, so every decision the march makes --
acceptance, the next proposal, the landing, the start-up rule, the caps, the floor, a
natural stop -- is a function of the scenario's data alone, with no field arithmetic.

The corpus ``tests/data/rk_traces.json.gz`` was generated by
``tests/data/generate_rk_traces.py`` from the march as it stood before SEP 45's
refactor into a pure controller core. The refactored Python march and the native march
must both reproduce it exactly, so that a mistake in the extraction cannot be blessed
in both halves (SEP 39 R1, which SEP 45 follows).

A scenario is plain data: the controller's fields, the stepper settings, the operator's
breakpoints and kinks, the caps the monitor hands the march (the quiet collar's
interval with its verdicts, a transverse edge's ceiling, the split collar's crossing
cap), the march targets, an optional prescribed schedule and the norms. :mod:`json`
writes a float as its shortest exact representation and reads it back bit for bit, so
the comparison is exact.
"""

from __future__ import annotations

import math
import sys
from collections import deque
from dataclasses import dataclass, field
from typing import Any

import numpy as np

from solprop.backends.driver import StepDriver, reached
from solprop.backends.rk_core import RungeKuttaPolicy
from solprop.exceptions import BackendError, ConvergenceError
from solprop.stepper.controller import PIController
from solprop.stepper.schedule import FixedSchedule

__all__ = ["Scenario", "run_scenario"]


@dataclass
class Scenario:
    """One scripted Runge-Kutta march (see the module docstring).

    Attributes
    ----------
    name : str
        A label.
    controller : dict
        Keyword arguments of :class:`~solprop.stepper.controller.PIController`.
    z0, proposal : float
        The starting position and first proposal, m.
    dz_min, dz_max, z_end, stretch : float
        The stepper settings.
    norms : list of float
        Per attempt, the scaled norm the trial returns, or with `h0` the noise that
        multiplies the model norm.
    h0 : float or None
        The step, m, at which the model norm ``(dz / h0) ** (q + 1)`` is one; a trial
        then returns ``noise * (dz / h0) ** (q + 1)``, as a real trial's norm grows
        with its step. ``None`` returns the scripted norms as they are.
    auto_init : bool
        Whether the start-up rule applies to the first accepted step.
    interval_cap : bool
        Whether every Chebyshev interval caps a step, or only the table's two ends.
    save_planes : list of float
        The save planes, which are also the march targets unless `targets` is given.
    breakpoints, kinks : list of float
        The operator's interval edges and hard kinks.
    step_planes : int
        Save every this many accepted steps (``0`` for none).
    quiet : dict
        Accepted-step count -> the monitor's quiet verdict from then on.
    quiet_interval : float or None
        The monitor's interval, m, that caps a step while the collar is quiet.
    ceiling : float or None
        A transverse edge's read spacing, m, capping every step; ``None`` for none.
    split : dict
        Accepted-step count -> the split collar's crossing cap from then on, m.
    targets : list of float or None
        The march targets in order; ``None`` takes the save planes, then `z_end`.
    schedule : list of float or None
        A prescribed schedule's steps; ``None`` for an adaptive march.
    """

    name: str
    controller: dict[str, Any]
    z0: float
    proposal: float
    dz_min: float
    dz_max: float
    z_end: float
    norms: list[float]
    h0: float | None = None
    stretch: float = 1.1
    auto_init: bool = True
    interval_cap: bool = False
    save_planes: list[float] = field(default_factory=list)
    breakpoints: list[float] = field(default_factory=list)
    kinks: list[float] = field(default_factory=list)
    step_planes: int = 0
    quiet: dict[int, bool] = field(default_factory=dict)
    quiet_interval: float | None = None
    ceiling: float | None = None
    split: dict[int, float] = field(default_factory=dict)
    targets: list[float] | None = None
    schedule: list[float] | None = None

    def to_json(self) -> dict[str, Any]:
        """Return the scenario as exact JSON data.

        Returns
        -------
        dict
            Every field, the dictionaries' integer keys as strings.
        """
        data = {name: getattr(self, name) for name in self.__dataclass_fields__}
        data["quiet"] = {str(key): value for key, value in self.quiet.items()}
        data["split"] = {str(key): value for key, value in self.split.items()}
        return data

    @classmethod
    def from_json(cls, data: dict[str, Any]) -> Scenario:
        """Read a scenario written by :meth:`to_json`.

        Parameters
        ----------
        data : dict
            The JSON data.

        Returns
        -------
        Scenario
            The scenario, floats bit for bit.
        """
        values = dict(data)
        values["quiet"] = {int(key): value for key, value in values["quiet"].items()}
        values["split"] = {int(key): value for key, value in values["split"].items()}
        return cls(**values)


class _ExhaustedError(Exception):
    """The scenario's norms ran out: its march ends there."""


class _Namespace:
    """Attributes from keywords."""

    def __init__(self, **values: Any) -> None:
        self.__dict__.update(values)


class _Edge:
    """A transverse edge's read spacing, the one part of it the march's cap reads."""

    def __init__(self, ceiling: float) -> None:
        self.spacing = ceiling

    def ceiling(self, z: float) -> float:
        """Return the step ceiling at `z`, m."""
        return self.spacing


class _Monitor:
    """The boundary monitor's interval, crossing cap and transverse edge: the parts
    of it the march's caps read."""

    def __init__(self, interval: float, ceiling: float | None) -> None:
        self.interval = interval
        self.step_cap = math.inf
        self.transverse = None if ceiling is None else _Edge(ceiling)


class _Harness(StepDriver):
    """A stub backend: the driver surface the Runge-Kutta march calls, recording it.

    Built without the driver's initialiser, which needs a translated problem; the march
    reads only the members set here and the methods overridden below.
    """

    name = "scripted"
    helpers = None  # pyright: ignore[reportAssignmentType]

    def __init__(self, scenario: Scenario) -> None:
        self.scenario = scenario
        controller = PIController(**scenario.controller)
        breakpoints = scenario.breakpoints or [scenario.z0, scenario.z_end]
        self._problem = _Namespace(  # pyright: ignore[reportAttributeAccessIssue]
            stepper=_Namespace(
                controller=controller,
                interpolate_planes=False,
                interval_cap=scenario.interval_cap,
                save_planes=np.array(scenario.save_planes, dtype=np.float64),
                dz_min=scenario.dz_min,
                dz_max=scenario.dz_max,
                z_end=scenario.z_end,
                stretch=scenario.stretch,
                auto_init=scenario.auto_init,
                step_planes=scenario.step_planes,
            ),
            linear=_Namespace(
                phi_breakpoints=np.array(breakpoints, dtype=np.float64),
                hard_kinks=np.array(scenario.kinks, dtype=np.float64),
            ),
        )
        self._z = scenario.z0
        self._proposal = scenario.proposal
        self._accepted_norms = deque(maxlen=controller.lag + 2)
        self._collar_quiet = scenario.quiet.get(0, False)
        monitor = None
        if scenario.quiet_interval is not None or scenario.ceiling or scenario.split:
            monitor = _Monitor(
                math.inf
                if scenario.quiet_interval is None
                else scenario.quiet_interval,
                scenario.ceiling,
            )
            monitor.step_cap = scenario.split.get(0, math.inf)
        self._monitor = monitor  # pyright: ignore[reportAttributeAccessIssue]
        self.stub_monitor = monitor
        self.controller = controller
        self.order = controller.estimator_order + 1
        self._stop = None
        self._dense_ahead = None
        self._natural_count = 0
        self._halt_requested = False
        self._natural_due = False
        self._schedule_index = 0
        self._state: object = "state"
        self.accepted = 0
        self.attempts = 0
        self.pending: dict[str, Any] = {}
        self.events: list[dict[str, Any]] = []

    # The driver's abstract members the march does not call.

    def _apply_mask(self, state: Any) -> Any:
        raise NotImplementedError

    def stats(self, spec: Any) -> Any:
        raise NotImplementedError

    # The driver surface the march uses.

    def _trial_step(self, z: float, dz: float) -> tuple[float, object]:
        self.close()
        index = self.attempts
        if index >= len(self.scenario.norms):
            raise _ExhaustedError
        self.pending = {"z": z, "dz": dz}
        self.attempts += 1
        noise = float(self.scenario.norms[index])
        h0 = self.scenario.h0
        if h0 is None:
            return noise, "advanced"
        return noise * (dz / h0) ** self.order, "advanced"

    def _controller_policy(self) -> RungeKuttaPolicy:
        stepper = self.scenario
        return RungeKuttaPolicy(
            controller=self.controller,
            dz_min=stepper.dz_min,
            dz_max=stepper.dz_max,
            auto_init=stepper.auto_init,
        )

    def _finish(self, state: Any, dz: float) -> Any:
        return state

    def _take_step_stats(self) -> None:
        self.accepted += 1
        scenario = self.scenario
        self._collar_quiet = scenario.quiet.get(self.accepted, self._collar_quiet)
        monitor = self.stub_monitor
        if monitor is not None:
            monitor.step_cap = scenario.split.get(self.accepted, monitor.step_cap)

    def _record(self, z: float, dz: float, norm: float, accepted: bool) -> None:
        row = dict(self.pending)
        row.update(
            end=z,
            step=dz,
            norm=norm if math.isfinite(norm) else math.inf,
            accepted=accepted,
        )
        self.events.append(row)
        self.pending = {}

    def close(self) -> None:
        """Attach the controller's state to the last attempt, its effect done."""
        if self.events and "after" not in self.events[-1] and "end" in self.events[-1]:
            self.events[-1]["after"] = self.snapshot()

    def snapshot(self) -> dict[str, Any]:
        """Return the controller's state after an attempt or a target."""
        return {
            "position": self._z,
            "proposal": self._proposal,
            "norms": [
                value if math.isfinite(value) else math.inf
                for value in self._accepted_norms
            ],
            "accepted": self.accepted,
            "natural": self._natural_count,
            "quiet": self._collar_quiet,
            "cursor": self._schedule_index,
        }


def run_scenario(scenario: Scenario) -> dict[str, Any]:
    """Run a scenario through the current Runge-Kutta march and return its trace.

    Parameters
    ----------
    scenario : Scenario
        The scripted march.

    Returns
    -------
    dict
        ``events``, one entry per attempt (with the controller's state after it) and
        per target reached, in order, and ``end``: how the march stopped (``"done"``
        or the exception's class and message) with the controller's state at that
        point, including any attempt left in flight.
    """
    harness = _Harness(scenario)
    if scenario.targets is not None:
        targets = list(scenario.targets)
    elif not scenario.save_planes:
        targets = [scenario.z_end]
    else:
        targets = sorted({*scenario.save_planes, scenario.z_end})
    schedule = (
        None
        if scenario.schedule is None
        else FixedSchedule(np.array(scenario.schedule, dtype=np.float64))
    )
    end: dict[str, Any] = {"stop": "done"}
    try:
        for target in targets:
            while True:
                if schedule is None:
                    harness._march_to(target)
                else:
                    harness._replay_to(schedule, target)
                harness.close()
                harness.events.append({"target": target, **harness.snapshot()})
                # A natural stop returns short of the target; carry on to it.
                if reached(harness._z, target):
                    break
    except _ExhaustedError:
        end = {"stop": "exhausted"}
    except (BackendError, ConvergenceError) as error:
        end = {"stop": type(error).__name__, "message": str(error)}
    harness.close()
    end["in_flight"] = dict(harness.pending)
    end.update(harness.snapshot())
    return {"events": harness.events, "end": end}


EXACT_LIBM = sys.platform.startswith("linux")
"""Whether this platform's ``pow`` is glibc's, which recorded the corpus.

The controller's factors are powers with non-integer exponents, which C libraries
round differently in the last place; a one-ulp factor moves every later proposal by a
few ulps. On glibc the corpus holds exactly; elsewhere the decisions -- every
acceptance, count and stop -- hold exactly and the positions, steps and norms to
:data:`LIBM_RTOL`.
"""

LIBM_RTOL = 1e-9
"""The relative tolerance of a trace's numbers on a C library other than glibc's."""


def same_trace(found: Any, expected: Any) -> bool:
    """Return whether two traces agree, exactly where the C library is glibc."""
    if EXACT_LIBM:
        return found == expected
    return _close(found, expected)


def _close(found: Any, expected: Any) -> bool:
    if isinstance(expected, dict):
        return (
            isinstance(found, dict)
            and found.keys() == expected.keys()
            and all(_close(found[key], expected[key]) for key in expected)
        )
    if isinstance(expected, list):
        return (
            isinstance(found, list)
            and len(found) == len(expected)
            and all(_close(a, b) for a, b in zip(found, expected, strict=True))
        )
    if isinstance(expected, float) and isinstance(found, float):
        return math.isclose(found, expected, rel_tol=LIBM_RTOL, abs_tol=0.0) or (
            math.isnan(found) and math.isnan(expected)
        )
    if isinstance(expected, str) and isinstance(found, str) and "e-" in expected:
        # A floor's message formats its proposal to four figures.
        return found.split(" asked for ")[0] == expected.split(" asked for ")[0]
    return found == expected
