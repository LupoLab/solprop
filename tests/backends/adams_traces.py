"""Decision traces of the Adams march on scripted norms (SEP 39 section 7.1).

The march's controller is driven through a stub backend and a stub engine. The engine
returns, for each attempt, the norms a scenario prescribes, so every decision the
march makes -- acceptance, the next order and proposal, the landing, a restart, the
call ledger -- is a function of the scenario's data alone, with no field arithmetic.

The corpus ``tests/data/adams_traces.json.gz`` was generated by
``tests/data/generate_adams_traces.py`` from the march as it stood before SEP 39's
refactor into a pure controller core. The refactored Python march and the native march
must both reproduce it exactly, so that a mistake in the extraction cannot be blessed
in both halves (SEP 39 R1).

A scenario is plain data: the method's fields, the stepper settings, the operator's
breakpoints and kinks, the in-stage collar's rate and the quiet verdicts the monitor
hands the march, an optional carrier chord, the march targets, an optional prescribed
schedule and the norms. :mod:`json` writes a float as its shortest exact
representation and reads it back bit for bit, so the comparison is exact.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from typing import Any

import numpy as np

from solprop._helpers import PLAIN
from solprop.backends.driver import StepDriver
from solprop.backends.exponential import CarrierChord, CarrierReference
from solprop.backends.multistep import AdamsKernels, AdamsMarch, ExponentialKernels
from solprop.exceptions import BackendError, ConvergenceError, ResponseBudgetError
from solprop.stepper.multistep import Multistep
from solprop.stepper.schedule import FixedSchedule

__all__ = ["LEDGER", "Scenario", "run_scenario"]


@dataclass
class Scenario:
    """One scripted march (see the module docstring).

    Attributes
    ----------
    name : str
        A label.
    method : dict
        Keyword arguments of :class:`~solprop.stepper.multistep.Multistep`.
    z0, proposal : float
        The starting position and first proposal, m.
    dz_min, dz_max, z_end, stretch : float
        The stepper settings.
    save_planes : list of float
        The save planes, which are also the march targets unless `targets` is given.
    interpolate : bool
        Whether planes are observed densely (stepped across, not landed on).
    breakpoints, kinks : list of float
        The operator's interval edges and hard kinks.
    norms : list of list of float
        Per attempt, the norms of the scored orders in the march's order; an attempt
        takes as many as it scores.
    collar_rate : float
        The in-stage collar's largest rate over two, m^-1; zero for none.
    quiet : dict
        Accepted-step count -> the monitor's quiet verdict from then on.
    quiet_interval : float or None
        The monitor's interval, m, that caps a step while the collar is quiet.
    carrier_rate : float or None
        A carrier chord's phase per metre; ``None`` for no carrier frame.
    targets : list of float or None
        The march targets in order; ``None`` takes the save planes, then `z_end`.
    schedule : list of float or None
        A prescribed schedule's steps; ``None`` for an adaptive march.
    """

    name: str
    method: dict[str, Any]
    z0: float
    proposal: float
    dz_min: float
    dz_max: float
    z_end: float
    norms: list[list[float]]
    stretch: float = 1.1
    save_planes: list[float] = field(default_factory=list)
    interpolate: bool = False
    breakpoints: list[float] = field(default_factory=list)
    kinks: list[float] = field(default_factory=list)
    collar_rate: float = 0.0
    quiet: dict[int, bool] = field(default_factory=dict)
    quiet_interval: float | None = None
    carrier_rate: float | None = None
    targets: list[float] | None = None
    schedule: list[float] | None = None

    def to_json(self) -> dict[str, Any]:
        """Return the scenario as exact JSON data.

        Returns
        -------
        dict
            Every field, the quiet verdicts' keys as strings.
        """
        data = {name: getattr(self, name) for name in self.__dataclass_fields__}
        data["quiet"] = {str(key): value for key, value in self.quiet.items()}
        return data

    @classmethod
    def from_json(cls, data: dict[str, Any]) -> Scenario:
        """Read a scenario written by :meth:`to_json`.

        Parameters
        ----------
        data : dict
            The JSON data.

        Returns
        -------
        Scenario
            The scenario, floats bit for bit.
        """
        values = dict(data)
        values["quiet"] = {int(key): value for key, value in values["quiet"].items()}
        return cls(**values)


class _Engine:
    """The engine a march hands its state-sized work to, replaced by a script."""

    def __init__(self, harness: _Harness, method: Multistep) -> None:
        self.harness = harness
        self.n_slots = method.order + 2
        self.dense = None
        rate = harness.scenario.carrier_rate
        self.carrier = (
            None
            if rate is None
            else CarrierReference(
                policy="scalar",
                bin=0,
                omega=1.0,
                reason="scripted",
                # A constant operator whose reference element turns by `rate` per
                # metre: the chord's phase over a step is `rate` times its length.
                chord=CarrierChord(constant=np.array([1j * rate])),
            )
        )

    def reset(self) -> None:
        """Forget nothing: the script holds no state."""

    def start(self, z: float, *, stored: bool) -> None:
        """Record a startup evaluation; a resident engine keeps the sample itself."""
        self.harness.events.append({"start": z, "stored": stored})

    def value(self, slot: int) -> None:
        """Return no host sample, as a resident engine does."""

    def exponential_trial(
        self,
        z: float,
        dz: float,
        nodes: list[float],
        slots: np.ndarray,
        order: int,
        orders: list[int],
    ) -> np.ndarray:
        """Return the scenario's norms for this attempt and record its stencil."""
        harness = self.harness
        index = harness.attempts
        if index >= len(harness.scenario.norms):
            msg = f"scenario {harness.scenario.name!r} ran out of norms"
            raise RuntimeError(msg)
        harness.pending = {
            "z": z,
            "dz": dz,
            "nodes": [float(node) for node in nodes],
            "slots": [int(slot) for slot in slots],
            "order": order,
            "orders": list(orders),
        }
        harness.attempts += 1
        return np.array(harness.scenario.norms[index][: len(orders)], dtype=np.float64)

    def exponential_accept(
        self, rows: np.ndarray, free: int, *, interpolate: bool
    ) -> None:
        """Record which rows the accepted step keeps and where the new one goes."""
        self.harness.pending["kept"] = [int(row) for row in rows]
        self.harness.pending["free"] = int(free)

    def hold(self) -> object:
        """Return a placeholder for the held state."""
        return "held"

    def restore(self, z: float, held: object) -> None:
        """Put the march back where it was held."""
        self.harness._z = z

    def observe(self, position: float) -> object:
        """Return a placeholder observation."""
        return "observed"


class _Problem:
    """The parts of a kernel problem the march reads."""

    def __init__(self, scenario: Scenario) -> None:
        breakpoints = scenario.breakpoints or [scenario.z0, scenario.z_end]
        self.stepper = _Namespace(
            interpolate_planes=scenario.interpolate,
            schedule=None
            if scenario.schedule is None
            else FixedSchedule(np.array(scenario.schedule, dtype=np.float64)),
            save_planes=np.array(scenario.save_planes, dtype=np.float64),
            dz_min=scenario.dz_min,
            dz_max=scenario.dz_max,
            z_end=scenario.z_end,
            stretch=scenario.stretch,
        )
        self.linear = _Namespace(
            phi_breakpoints=np.array(breakpoints, dtype=np.float64),
            hard_kinks=np.array(scenario.kinks, dtype=np.float64),
        )
        self.responses = _Namespace(
            temporal_absorber=None
            if scenario.collar_rate == 0.0
            else np.array([2.0 * scenario.collar_rate]),
            absorber_scheme="nonlinear",
        )
        self.shape = (1, 1, 1, 1)


class _Namespace:
    """Attributes from keywords."""

    def __init__(self, **values: Any) -> None:
        self.__dict__.update(values)


class _Monitor:
    """The boundary monitor's interval, the only part the march's caps read."""

    def __init__(self, interval: float) -> None:
        self.interval = interval


class _Harness(StepDriver):
    """A stub backend: the driver surface :class:`AdamsMarch` calls, recording it.

    Built without the driver's initialiser, which needs a translated problem; the march
    reads only the members set here and the methods overridden below.
    """

    name = "scripted"
    helpers = None  # pyright: ignore[reportAssignmentType]

    def __init__(self, scenario: Scenario) -> None:
        self.scenario = scenario
        self._problem = _Problem(scenario)
        self._z = scenario.z0
        self._proposal = scenario.proposal
        self._collar_quiet = scenario.quiet.get(0, False)
        self._monitor = (
            None
            if scenario.quiet_interval is None
            else _Monitor(scenario.quiet_interval)
        )
        self._schedule_index = 0
        self._accepted_norms: list[float] = []
        self._state: object = "state"
        self.accepted = 0
        self.attempts = 0
        self.pending: dict[str, Any] = {}
        self.events: list[dict[str, Any]] = []
        self.engine: _Engine | None = None
        self.march: AdamsMarch | None = None

    # The driver's abstract members, which the march never calls.

    def _trial_step(self, z: float, dz: float) -> Any:
        raise NotImplementedError

    def _apply_mask(self, state: Any) -> Any:
        raise NotImplementedError

    def stats(self, spec: Any) -> Any:
        raise NotImplementedError

    # The driver surface the march uses.

    def _adams_engine(self, method: Multistep, compensation: str) -> _Engine:
        self.engine = _Engine(self, method)
        return self.engine

    def _adams_state(self) -> np.ndarray:
        return np.zeros((1, 1, 1, 1), dtype=np.complex128)

    def _reserve_source_calls(self, cost: int) -> None:
        pass

    def _release_source_calls(self) -> None:
        pass

    def _natural_stop_due(self, target: float) -> bool:
        return False

    def _natural_stop(self, target: float) -> bool:
        return False

    def _quiet_capped(self, proposal: float) -> float:
        if not self._collar_quiet or self._monitor is None:
            return proposal
        return min(proposal, self._monitor.interval)

    def _take_step_stats(self) -> None:
        self.accepted += 1
        self._collar_quiet = self.scenario.quiet.get(self.accepted, self._collar_quiet)

    def _record(self, end: float, dz: float, norm: float, accepted: bool) -> None:
        march = self.march
        assert march is not None
        row = dict(self.pending)
        row.update(
            end=end,
            step=dz,
            norm=norm if math.isfinite(norm) else math.inf,
            accepted=accepted,
            **_march_state(self, march),
        )
        self.events.append(row)
        self.pending = {}


LEDGER = (
    "startup",
    "predictor",
    "rejected",
    "accepted_steps",
    "rejected_steps",
    "restarts",
    "failure_restarts",
    "dense_observations",
)
"""The call ledger's counters, in the order a trace lists them."""


def _march_state(harness: _Harness, march: AdamsMarch) -> dict[str, Any]:
    """Return the march's controller state after an attempt.

    Parameters
    ----------
    harness : _Harness
        The stub backend.
    march : AdamsMarch
        The march.

    Returns
    -------
    dict
        Position, proposal, stored order, rejection count, the two flags, the history
        as ``[z, identity, row]`` entries and the ledger's counters (:data:`LEDGER`).
    """
    ledger = march.ledger
    return {
        "position": harness._z,
        "proposal": harness._proposal,
        "stored_order": march._order,
        "rejections": march._rejections,
        "last_rejected": march._last_rejected,
        "collar_was_quiet": march._collar_was_quiet,
        "quiet": harness._collar_quiet,
        "history": [[entry.z, entry.identity, entry.slot] for entry in march._history],
        "ledger": [getattr(ledger, name) for name in LEDGER],
    }


def run_scenario(scenario: Scenario) -> dict[str, Any]:
    """Run a scenario through the current :class:`AdamsMarch` and return its trace.

    Parameters
    ----------
    scenario : Scenario
        The scripted march.

    Returns
    -------
    dict
        ``events``, one entry per startup and per attempt in order, and ``end``: how
        the march stopped (``"done"`` or the exception's class and message) with the
        controller's state at that point, including any attempt left in flight.
    """
    harness = _Harness(scenario)
    method = Multistep(formulation="exponential", **scenario.method)
    # Real kernels, which the scripted engine never calls.
    march = AdamsMarch(
        harness,
        method,
        kernels=AdamsKernels(helpers=PLAIN),
        exponential=ExponentialKernels(helpers=PLAIN),
    )
    harness.march = march
    if scenario.targets is not None:
        targets = list(scenario.targets)
    elif scenario.interpolate or not scenario.save_planes:
        targets = [scenario.z_end]
    else:
        targets = [*scenario.save_planes, scenario.z_end]
        targets = sorted(set(targets))
    end: dict[str, Any] = {"stop": "done"}
    try:
        for target in targets:
            march.march_to(target)
            harness.events.append({"target": target, "position": harness._z})
    except (BackendError, ConvergenceError, ResponseBudgetError) as error:
        end = {"stop": type(error).__name__, "message": str(error)}
    end["in_flight"] = dict(harness.pending)
    end.update(_march_state(harness, march))
    end["orders"] = list(march.ledger.orders)
    return {"events": harness.events, "end": end}
