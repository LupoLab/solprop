from solprop.backends.host.adams import HostAdamsMarch
from solprop.backends.host.marches import MarchState
from solprop.backends.host.session import step_cap
from solprop.backends.records import adams_policy
from solprop.exceptions import BackendError, ConvergenceError, ResponseBudgetError
from solprop.stepper.multistep import Formulation, Multistep
from solprop.stepper.schedule import FixedSchedule

__all__ = ["LEDGER", "Scenario", "run_scenario"]


@dataclass
class Scenario:
    """One scripted march (see the module docstring).

    Attributes
    ----------
    name : str
        A label.
    method : dict
        Keyword arguments of :class:`~solprop.stepper.multistep.Multistep`.
    z0, proposal : float
        The starting position and first proposal, m.
    dz_min, dz_max, z_end, stretch : float
        The stepper settings.
    save_planes : list of float
        The save planes, which are also the march targets unless `targets` is given.
    interpolate : bool
        Whether planes are observed densely (stepped across, not landed on).
    breakpoints, kinks : list of float
        The operator's interval edges and hard kinks.
    norms : list of list of float
        Per attempt, the norms of the scored orders in the march's order; an attempt
        takes as many as it scores.
    collar_rate : float
        The in-stage collar's largest rate over two, m^-1; zero for none.
    quiet : dict
        Accepted-step count -> the monitor's quiet verdict from then on.
    quiet_interval : float or None
        The monitor's interval, m, that caps a step while the collar is quiet.
    carrier_rate : float or None
        A carrier chord's phase per metre; ``None`` for no carrier frame.
    targets : list of float or None
        The march targets in order; ``None`` takes the save planes, then `z_end`.
    schedule : list of float or None
        A prescribed schedule's steps; ``None`` for an adaptive march.
    """

    name: str
    method: dict[str, Any]
    z0: float
    proposal: float
    dz_min: float
    dz_max: float
    z_end: float
    norms: list[list[float]]
    stretch: float = 1.1
    save_planes: list[float] = field(default_factory=list)
    interpolate: bool = False
    breakpoints: list[float] = field(default_factory=list)
    kinks: list[float] = field(default_factory=list)
    collar_rate: float = 0.0
    quiet: dict[int, bool] = field(default_factory=dict)
    quiet_interval: float | None = None
    carrier_rate: float | None = None
    targets: list[float] | None = None
    schedule: list[float] | None = None

    def to_json(self) -> dict[str, Any]:
        """Return the scenario as exact JSON data.

        Returns
        -------
        dict
            Every field, the quiet verdicts' keys as strings.
        """
        data = {name: getattr(self, name) for name in self.__dataclass_fields__}
        data["quiet"] = {str(key): value for key, value in self.quiet.items()}
        return data

    @classmethod
    def from_json(cls, data: dict[str, Any]) -> Scenario:
        """Read a scenario written by :meth:`to_json`.

        Parameters
        ----------
        data : dict
            The JSON data.

        Returns
        -------
        Scenario
            The scenario, floats bit for bit.
        """
        values = dict(data)
        values["quiet"] = {int(key): value for key, value in values["quiet"].items()}
        return cls(**values)


class _Engine:
    """The engine a march hands its state-sized work to, replaced by a script."""

    def __init__(self, harness: _Scripted, method: Multistep) -> None:
        self.harness = harness
        self.formulation = method.formulation
        self.n_slots = method.order + 2
        self.dense = None
        rate = harness.scenario.carrier_rate
        self.carrier = (
            None
            if rate is None
            else CarrierReference(
                policy="scalar",
                bin=0,
                omega=1.0,
                reason="scripted",
                # A constant operator whose reference element turns by `rate` per
                # metre: the chord's phase over a step is `rate` times its length.
                chord=CarrierChord(constant=np.array(1j * rate)),
            )
        )

    def reset(self) -> None:
        """Forget nothing: the script holds no state."""

    def start(self, z: float) -> None:
        """Record a startup evaluation; a resident engine keeps the sample itself."""
        # Every startup sample is stored since the comparison variants went, as the
        # native march logs it.
        self.harness.events.append({"start": z, "stored": True})

    def value(self, slot: int) -> None:
        """Return no host sample, as a resident engine does."""

    # The engine protocol (`solprop.backends.engines.AdamsEngine`) the reference's
    # march calls; the native adapter calls the per-formulation members below.

    def trial(self, z: float, dz: float, stencil: Any) -> np.ndarray:
        """Return the scenario's norms for an attempt of the method's formulation."""
        return self._trial(
            self.formulation,
            z,
            dz,
            stencil.nodes,
            stencil.rows,
            stencil.order,
            stencil.orders,
        )

    def accept(self, dz: float, free: int, stencil: Any, kept: Any) -> AcceptRecord:
        """Record which rows the accepted step keeps and where the new one goes."""
        del dz, stencil
        rows = np.array([entry.row for entry in kept], dtype=np.int64)
        self._accept(self.formulation, rows, free)
        return AcceptRecord()

    def chord_phase(self, z1: float, z2: float) -> float:
        """Return the scripted carrier chord's phase over the interval."""
        assert self.carrier is not None
        return self.carrier.chord_phase(z1, z2)

    def step_carrier(self, order: int) -> np.ndarray:
        """Return no rotations: the script holds no field."""
        del order
        return np.zeros(0)

    def begin_attempt(self, cost: int) -> None:
        """Reserve nothing: no host source is bound."""

    def end_attempt(self, outcome: Any) -> None:
        """Release nothing."""

    def reading(self) -> Any:
        """Refuse: the scenarios watch no boundary."""
        raise NotImplementedError

    def exponential_trial(
        self,
        z: float,
        dz: float,
        nodes: list[float],
        slots: np.ndarray,
        order: int,
        orders: list[int],
    ) -> np.ndarray:
        """Return the scenario's norms for an exponential attempt (:meth:`_trial`)."""
        return self._trial("exponential", z, dz, nodes, slots, order, orders)

    def fused_trial(
        self,
        z: float,
        dz: float,
        nodes: list[float],
        slots: np.ndarray,
        order: int,
        orders: list[int],
    ) -> np.ndarray:
        """Return the scenario's norms for a fused attempt (:meth:`_trial`)."""
        return self._trial("interaction", z, dz, nodes, slots, order, orders)

    def _trial(
        self,
        formulation: str,
        z: float,
        dz: float,
        nodes: list[float],
        slots: np.ndarray,
        order: int,
        orders: list[int],
    ) -> np.ndarray:
        """Return the scenario's norms for this attempt and record its stencil.

        The trial of the method's own formulation only: a march that asked the other
        family's trial would pass a decision trace, which holds no field arithmetic,
        while taking the wrong path.
        """
        harness = self.harness
        if formulation != self.formulation:
            msg = f"a {self.formulation} march asked for the {formulation} trial"
            raise AssertionError(msg)
        index = harness.attempts
        if index >= len(harness.scenario.norms):
            msg = f"scenario {harness.scenario.name!r} ran out of norms"
            raise RuntimeError(msg)
        harness.pending = {
            "z": z,
            "dz": dz,
            "nodes": [float(node) for node in nodes],
            "slots": [int(slot) for slot in slots],
            "order": order,
            "orders": list(orders),
        }
        harness.attempts += 1
        return np.array(harness.scenario.norms[index][: len(orders)], dtype=np.float64)

    def exponential_accept(
        self, rows: np.ndarray, free: int, *, interpolate: bool
    ) -> None:
        """Record an exponential acceptance (:meth:`_accept`)."""
        self._accept("exponential", rows, free)

    def fused_accept(self, rows: np.ndarray, free: int, *, interpolate: bool) -> None:
        """Record a fused acceptance (:meth:`_accept`)."""
        self._accept("interaction", rows, free)

    def _accept(self, formulation: str, rows: np.ndarray, free: int) -> None:
        """Record which rows the accepted step keeps and where the new one goes."""
        if formulation != self.formulation:
            msg = f"a {self.formulation} march asked for the {formulation} acceptance"
            raise AssertionError(msg)
        self.harness.pending["kept"] = [int(row) for row in rows]
        self.harness.pending["free"] = int(free)

    def hold(self) -> object:
        """Return a placeholder for the held state."""
        return "held"

    def restore(self, z: float, held: object) -> None:
        """Put the march back where it was held."""
        self.harness._z = z

    def observe(self, position: float) -> object:
        """Return a placeholder observation."""
        return "observed"


class _Problem:
    """The parts of a kernel problem, and of its run's stepper, the march reads."""

    def __init__(self, scenario: Scenario) -> None:
        breakpoints = scenario.breakpoints or [scenario.z0, scenario.z_end]
        self.stepper = _Namespace(
            interpolate_planes=scenario.interpolate,
            schedule=None
            if scenario.schedule is None
            else FixedSchedule(np.array(scenario.schedule, dtype=np.float64)),
            save_planes=np.array(scenario.save_planes, dtype=np.float64),
            dz_min=scenario.dz_min,
            dz_max=scenario.dz_max,
            z_end=scenario.z_end,
            stretch=scenario.stretch,
        )
        self.linear = _Namespace(
            phi_breakpoints=np.array(breakpoints, dtype=np.float64),
            hard_kinks=np.array(scenario.kinks, dtype=np.float64),
        )
        self.responses = _Namespace(
            temporal_absorber=None
            if scenario.collar_rate == 0.0
            else np.array([2.0 * scenario.collar_rate]),
            absorber_scheme="nonlinear",
        )
        self.shape = (1, 1, 1, 1)


class _Namespace:
    """Attributes from keywords."""

    def __init__(self, **values: Any) -> None:
        self.__dict__.update(values)


class _Monitor:
    """The boundary monitor's interval and crossing cap, the parts the march's caps
    read; no split collar caps these scenarios, and no transverse edge is watched."""

    step_cap = math.inf
    transverse = None

    def __init__(self, interval: float) -> None:
        self.interval = interval


class _Scripted:
    """A stub session: what the Adams marches ask of it, recording it.

    The reference's march asks through
    :class:`~solprop.backends.host.marches.MarchHost` (:class:`_HostHarness`); the
    native march's call-by-call adapter (``native_trace_marches.TraceAdamsMarch``)
    reads the members set here, in the names the reference's step driver had, so that
    the native march's decision traces are held to the reference's
    (``test_native_march_traces.py``).
    """

    name = "scripted"
    helpers = None  # pyright: ignore[reportAssignmentType]

    def __init__(self, scenario: Scenario) -> None:
        self.scenario = scenario
        self._problem = _Problem(scenario)
        # The run's stepper section, which the march reads off the backend.
        self._stepper = self._problem.stepper
        # The march's state, which the native adapter reads and writes through the
        # driver's names (the properties below); the reference's march holds it.
        self._shadow = MarchState(
            z=scenario.z0, proposal=scenario.proposal, norms=deque(maxlen=3)
        )
        self._collar_quiet = scenario.quiet.get(0, False)
        self._monitor = (  # pyright: ignore[reportAttributeAccessIssue]
            None
            if scenario.quiet_interval is None
            else _Monitor(scenario.quiet_interval)
        )
        self._state: object = "state"
        self.accepted = 0
        self.attempts = 0
        self.pending: dict[str, Any] = {}
        self.events: list[dict[str, Any]] = []
        self.engine: _Engine | None = None
        self.march: Any | None = None
        # The plane a dense observation holds, as the session observes it.
        self.observed: float | None = None

    def _held_state(self) -> MarchState:
        march = self.march
        state = getattr(march, "state", None)
        return state if isinstance(state, MarchState) else self._shadow

    @property
    def _z(self) -> float:
        return self._held_state().z

    @_z.setter
    def _z(self, value: float) -> None:
        self._held_state().z = value

    @property
    def _proposal(self) -> float:
        return self._held_state().proposal

    @_proposal.setter
    def _proposal(self, value: float) -> None:
        self._held_state().proposal = value

    @property
    def _schedule_index(self) -> int:
        return self._held_state().cursor

    @_schedule_index.setter
    def _schedule_index(self, value: int) -> None:
        self._held_state().cursor = value

    @property
    def _accepted_norms(self) -> deque[float]:
        return self._held_state().norms

    def stats(self, spec: Any) -> Any:
        raise NotImplementedError

    # The driver surface the march uses.

    def _adams_state(self) -> np.ndarray:
        return np.zeros((1, 1, 1), dtype=np.complex128)

    def _reserve_source_calls(self, count: int) -> None:
        pass

    def _release_source_calls(self) -> None:
        pass

    def _poll_stop(self) -> None:
        pass

    def _natural_stop_due(self, target: float) -> bool:
        return False

    def _natural_stop(self, target: float) -> bool:
        return False

    def _take_step_stats(self) -> None:
        self.accepted += 1
        self._collar_quiet = self.scenario.quiet.get(self.accepted, self._collar_quiet)

    def _record(self, z: float, dz: float, norm: float, accepted: bool) -> None:
        march = self.march
        assert march is not None
        row = dict(self.pending)
        row.update(
            end=z,
            step=dz,
            norm=norm if math.isfinite(norm) else math.inf,
            accepted=accepted,
            **_march_state(self, march),
        )
        self.events.append(row)
        self.pending = {}


class _HostHarness(_Scripted):
    """The stub hosting the reference's Adams march; the engine is given to it."""

    helpers = PLAIN

    # The march's host (`MarchHost`), with the session's rules.

    @property
    def collar_quiet(self) -> bool:
        return self._collar_quiet

    def poll_stop(self) -> None:
        self._poll_stop()

    def cap(self, proposal: float, z: float) -> float:
        return step_cap(self._monitor, self._collar_quiet, proposal, z)

    def record(self, end: float, dz: float, norm: float, accepted: bool) -> None:
        self._record(end, dz, norm, accepted)

    def absorb(self, record: AcceptRecord) -> None:
        del record

    def stepped(self) -> None:
        self._take_step_stats()

    def natural_stop(self, target: float) -> bool:
        return self._natural_stop(target)

    def adams_march(self, method: Multistep) -> HostAdamsMarch:
        """Return the reference's march over the scripted engine, at the start."""
        engine = self.engine
        assert engine is not None
        carrier = engine.carrier
        stepper: Any = self._stepper
        policy = adams_policy(
            cast("Any", self._problem),
            stepper,
            method,
            carrier=isinstance(carrier, CarrierReference) and carrier.active,
        )
        march = HostAdamsMarch(
            engine,
            method,
            self,
            policy=policy,
            field=lambda: np.zeros((1, 1, 1), dtype=np.complex128),
            schedule=stepper.schedule,
            interpolate=stepper.interpolate_planes,
            shape=(1, 1, 1),
            proposal=self.scenario.proposal,
            lag=1,
            name=self.name,
        )
        march.state.z = self.scenario.z0
        return march

    def _adams_engine(self, method: Multistep, compensation: str) -> _Engine:
        """Return a fresh scripted engine, for a march that asks its backend for one."""
        del compensation
        self.engine = _Engine(self, method)
        return self.engine


LEDGER = (
    "startup",
    "predictor",
    "rejected",
    "accepted_steps",
    "rejected_steps",
    "restarts",
    "failure_restarts",
    "dense_observations",
)
"""The call ledger's counters, in the order a trace lists them."""


def _march_state(harness: _Scripted, march: Any) -> dict[str, Any]:
    """Return the march's controller state after an attempt.

    Parameters
    ----------
    harness : _Scripted
        The stub backend.
    march : object
        The march: the reference's, or the native record driven a call at a time
        (``native_trace_marches.TraceAdamsMarch``).

    Returns
    -------
    dict
        Position, proposal, stored order, rejection count, the two flags, the history
        as ``[z, identity, row]`` entries and the ledger's counters (:data:`LEDGER`).
    """
    ledger = march.ledger
    return {
        "position": harness._z if harness.observed is None else harness.observed,
        "proposal": harness._proposal,
        "stored_order": march._order,
        "rejections": march._rejections,
        "last_rejected": march._last_rejected,
        "collar_was_quiet": march._collar_was_quiet,
        "quiet": harness._collar_quiet,
        "history": [
            [
                entry.z,
                entry.identity,
                entry.row if hasattr(entry, "row") else entry.slot,
            ]
            for entry in march._history
        ],
        "ledger": [getattr(ledger, name) for name in LEDGER],
    }


def run_scenario(
    scenario: Scenario, *, formulation: Formulation = "exponential"
) -> dict[str, Any]:
    """Run a scenario through a Python Adams march and return its trace.

    Parameters
    ----------
    scenario : Scenario
        The scripted march.
    formulation : {'exponential', 'interaction'}, optional
        The method's formulation: the exponential trial, which the corpus was taken
        on, or the fused one (issue #270). The controller is the same; the fused path
        drops the in-stage collar's stability from its order choice.

    Returns
    -------
    dict
        ``events``, one entry per startup and per attempt in order, and ``end``: how
        the march stopped (``"done"`` or the exception's class and message) with the
        controller's state at that point, including any attempt left in flight.
    """
    method = Multistep(formulation=formulation, **scenario.method)
    harness = _HostHarness(scenario)
    harness.engine = _Engine(harness, method)
    march = harness.adams_march(method)
    harness.march = march
    if scenario.targets is not None:
        targets = list(scenario.targets)
    elif scenario.interpolate or not scenario.save_planes:
        targets = [scenario.z_end]
    else:
        targets = [*scenario.save_planes, scenario.z_end]
        targets = sorted(set(targets))
    end: dict[str, Any] = {"stop": "done"}
    try:
        for target in targets:
            # The session restores a held plane's committed state before it marches.
            harness.observed = None
            march.march_to(target)
            if scenario.interpolate and march.state.z > target:
                # The session observes the plane inside the step that crossed it
                # (`AdamsDense.crosses`), holding the committed state aside.
                harness.observed = target
                march.ledger.dense_observations += 1
            harness.events.append(
                {"target": target, "position": _march_state(harness, march)["position"]}
            )
    except (BackendError, ConvergenceError, ResponseBudgetError) as error:
        end = {"stop": type(error).__name__, "message": str(error)}
    end["in_flight"] = dict(harness.pending)
    end.update(_march_state(harness, march))
    end["orders"] = list(march.ledger.orders)
    return {"events": harness.events, "end": end}
