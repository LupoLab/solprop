ROOT = Path(__file__).resolve().parents[1]


class _Item:
    def __init__(self, nodeid, *groups):
        self.nodeid = nodeid
        self.stash = pytest.Stash()
        self.groups = list(groups)

    def get_closest_marker(self, name):
        assert name == "xdist_group"
        return self.groups[0] if self.groups else None

    def add_marker(self, marker):
        assert marker.name == "xdist_group"
        self.groups.append(marker)


@pytest.fixture
def collection_plugin(pytestconfig):
    plugin = pytestconfig.pluginmanager.get_plugin(str(ROOT / "tests/conftest.py"))
    assert plugin is not None
    return plugin


def test_default_groups_share_a_module_across_classes_and_parameters(collection_plugin):
    items = [
        _Item("tests/test_one.py::test_first[a@b]"),
        _Item("tests/test_one.py::TestMore::test_second"),
        _Item("tests/test_two.py::test_third"),
        _Item("src/solprop/example.py::solprop.example.function"),
    ]
    collection_plugin._group_items_by_module(items)
    assert [item.groups[0].kwargs["name"] for item in items] == [
        "module:tests/test_one.py",
        "module:tests/test_one.py",
        "module:tests/test_two.py",
        "module:src/solprop/example.py",
    ]
    assert all(len(item.groups) == 1 for item in items)


@pytest.mark.parametrize(
    "groups",
    [
        (pytest.mark.xdist_group("explicit"),),
        (pytest.mark.xdist_group(name="explicit"),),
        (pytest.mark.xdist_group("fixture"), pytest.mark.xdist_group("case")),
    ],
)
def test_explicit_groups_are_not_joined_to_the_module(collection_plugin, groups):
    item = _Item("tests/test_one.py::test_first", *groups)
    collection_plugin._group_items_by_module([item])
    assert item.groups == list(groups)


@pytest.mark.parametrize(
    ("distribution", "worker_group", "grouped"),
    [
        ("no", False, False),
        ("loadfile", False, False),
        ("loadgroup", False, True),
        ("no", True, True),
    ],
)
def test_collection_preserves_original_tier_keys_and_serial_selection(
    collection_plugin, monkeypatch, distribution, worker_group, grouped
):
    recorded = {}
    monkeypatch.setattr(collection_plugin, "_COLLECTED_TIERS", recorded)
    item = _Item("tests/test_one.py::test_first")
    monkeypatch.setattr(
        item,
        "get_closest_marker",
        lambda name: pytest.mark.slow.mark if name == "slow" else None,
    )
    options = {"dist": distribution, "loadgroup": worker_group}
    config = SimpleNamespace(getoption=lambda name, **kwargs: options[name])
    collection_plugin.pytest_collection_modifyitems(config, [item])
    assert recorded == {"tests/test_one.py::test_first": ("slow",)}
    assert item.nodeid == "tests/test_one.py::test_first"
    assert bool(item.groups) is grouped


@pytest.mark.parametrize("identity", ["test.py::test_one", "test.py::test_one[a@b@c]"])
def test_original_identity_survives_scheduling_suffixes(identity):
    item = _Item(identity)
    assert original_nodeid(item) == identity
    remember_nodeid(item)
    item.nodeid += "@module:test.py"
    remember_nodeid(item)
    assert original_nodeid(item) == identity


@pytest.mark.parametrize("case", ["left@right"])
def test_grouped_record_identity_and_path_preserve_parameter_text(
    case, request, monkeypatch, tmp_path
):
    # The writer's existing tests use the same temporary clean-tree admission.
    # No committed witness is regenerated by this mechanism check.
    monkeypatch.setattr(cr, "RECORDS", tmp_path)
    monkeypatch.setattr(cr, "_WRITTEN", set())
    monkeypatch.setattr(cr, "dirty_paths", lambda: [])
    monkeypatch.setenv(cr.WRITE_ENV, "1")
    monkeypatch.delenv("CI", raising=False)
    monkeypatch.delenv("PYTEST_XDIST_WORKER", raising=False)
    study = cr.Study(
        "distribution",
        "distribution identity",
        {},
        {"name": "n", "unit": "1", "label": "case"},
        (cr.Column("value", "1", "exact synthetic value", rtol=0.0),),
    )
    rows = [{"series": case, "axis": 1, "value": 1.0}]
    record = cr.record(study, request=request, rows=rows)
    expected = (
        "tests/test_distribution.py::"
        "test_grouped_record_identity_and_path_preserve_parameter_text[left@right]"
    )
    assert record["rows"][0]["written_by"] == expected
    path = tmp_path / "distribution.json"
    assert list(tmp_path.iterdir()) == [path]
    original = path.read_bytes()
    monkeypatch.delenv(cr.WRITE_ENV)
    assert cr.record(study, request=request, rows=rows) == record
    assert path.read_bytes() == original
    assert list(tmp_path.iterdir()) == [path]


def _write_synthetic_suite(directory):
    source = (ROOT / "tests/conftest.py").read_text()
    (directory / "conftest.py").write_text(
        source
        + """


def pytest_sessionfinish(session):
    import json
    from pathlib import Path

    if hasattr(session.config, "workerinput"):
        worker = session.config.workerinput["workerid"]
        Path(f"collected-{worker}.json").write_text(json.dumps({
            "tiers": _COLLECTED_TIERS,
            "selected": [item.nodeid for item in session.items],
        }))
"""
    )
    (directory / "pytest.ini").write_text(
        "[pytest]\naddopts = --strict-markers -m 'not slow'\n"
        "markers = slow: deselected fixture\n"
    )
    (directory / "test_default.py").write_text(
        """from pathlib import Path

import pytest


@pytest.fixture(scope="module")
def shared(worker_id):
    path = Path(f"fixture-{worker_id}.txt")
    assert not path.exists(), "the module fixture was built twice on one worker"
    path.write_text(worker_id)
    return worker_id


@pytest.mark.parametrize("case", range(4))
def test_module_fixture(case, shared):
    Path(f"default-{case}.txt").write_text(shared)


@pytest.mark.slow
def test_deselected():
    raise AssertionError("distribution must not change tier selection")
"""
    )
    (directory / "test_spread.py").write_text(
        """import pytest


@pytest.mark.parametrize("case", range(4))
def test_free(case):
    pass
"""
    )
    (directory / "test_param.py").write_text(
        """import pytest


@pytest.fixture(scope="module", params=["x", "y"])
def table(request):
    return request.param


@pytest.mark.parametrize("case", range(2))
def test_table(case, table):
    pass
"""
    )
    (directory / "test_independent.py").write_text(
        """import time
from pathlib import Path

import pytest


def rendezvous(name, other, worker_id):
    Path(f"worker-{name}.txt").write_text(worker_id)
    # A guard against both groups landing on one worker, which would wait forever; not
    # a timing bound, so generous enough that a loaded machine's slow second worker
    # cannot trip it.
    deadline = time.monotonic() + 120
    while not Path(f"worker-{other}.txt").exists():
        if time.monotonic() >= deadline:
            pytest.fail("independent groups did not reach separate workers")
        time.sleep(0.01)


@pytest.mark.xdist_group("heavy-a")
@pytest.mark.parametrize("case", range(3))
def test_first(case, worker_id):
    if case == 0:
        rendezvous("a", "b", worker_id)


@pytest.mark.xdist_group(name="heavy-b")
@pytest.mark.parametrize("case", range(3))
def test_second(case, worker_id):
    if case == 0:
        rendezvous("b", "a", worker_id)
"""
    )


@pytest.mark.medium
def test_loadgroup_reuses_module_fixtures_and_spreads_independent_cases(tmp_path):
    _write_synthetic_suite(tmp_path)
    environment = {
        key: value
        for key, value in os.environ.items()
        if key
        not in {
            "PYTEST_XDIST_WORKER",
            "PYTEST_XDIST_WORKER_COUNT",
            "PYTEST_XDIST_TESTRUNUID",
            "PYTEST_ADDOPTS",
        }
    }
    environment["PYTEST_DISABLE_PLUGIN_AUTOLOAD"] = "1"
    environment["PYTHONPATH"] = os.pathsep.join(
        [str(ROOT / "tests"), str(ROOT / "src"), environment.get("PYTHONPATH", "")]
    )
    result = subprocess.run(
        [
            sys.executable,
            "-m",
            "pytest",
            "-p",
            "xdist.plugin",
            "-n",
            "2",
            "--dist",
            "loadgroup",
            "-q",
        ],
        cwd=tmp_path,
        env=environment,
        capture_output=True,
        text=True,
        # A hang guard only: the synthetic suite takes seconds, but starting two xdist
        # workers on a loaded machine has taken longer than a tight limit allows.
        timeout=600,
        check=False,
    )
    assert result.returncode == 0, result.stdout + result.stderr
    assert "18 passed" in result.stdout
    assert len(list(tmp_path.glob("fixture-*.txt"))) == 1
    default_workers = {
        (tmp_path / f"default-{case}.txt").read_text() for case in range(4)
    }
    assert len(default_workers) == 1
    assert (tmp_path / "worker-a.txt").read_text() != (
        tmp_path / "worker-b.txt"
    ).read_text()
    records = [
        json.loads(path.read_text()) for path in tmp_path.glob("collected-*.json")
    ]
    assert len(records) == 2 and records[0] == records[1]
    assert records[0]["tiers"]["test_default.py::test_deselected"] == ["slow"]
    assert len(records[0]["tiers"]) == 19
    assert all("@module:" not in node for node in records[0]["tiers"])
    selected = records[0]["selected"]
    assert len(selected) == 18
    # A test sharing no fixture is not grouped; one sharing a parametrised module
    # fixture is grouped with that parameter's tests alone.
    assert all("@" not in node for node in selected if "::test_free[" in node)
    assert {node.split("@", 1)[1] for node in selected if "::test_table[" in node} == {
        "module:test_param.py:table=0",
        "module:test_param.py:table=1",
    }
    assert all(
        node.endswith("@module:test_default.py")
        for node in selected
        if node.startswith("test_default.py::")
    )
    assert all(
        node.endswith("@heavy-a") for node in selected if "::test_first[" in node
    )
    assert all(
        node.endswith("@heavy-b") for node in selected if "::test_second[" in node
    )
